#pragma once

#include <time.h>

// ============================================================================
// 時刻 (NTP で合わせる)
//   Pico W には電池付きの時計がないので、電源を入れるたびに Wi-Fi 経由で合わせ直す。
//   SDカードに書くファイルのタイムスタンプに使う (合っていない間は 2000-01-01 を付ける)
// ============================================================================

// タイムゾーンの設定と、SDのタイムスタンプ用コールバックの登録 (起動時に1回)
void clock_init();

// NTP で時刻を合わせ始める (Wi-Fi 接続後に呼ぶ)。
// サーバー名の問い合わせ (DNS) で最大数秒止まるので、再生・録音中には呼ばない
void clock_start_ntp();

// NTP で時刻が合っているか
bool clock_is_valid();
